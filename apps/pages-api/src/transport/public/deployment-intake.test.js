import assert from 'node:assert/strict';
import test from 'node:test';

import { deploymentMultipartError, readDeploymentIntakeHeaders, readRollbackIntake } from './deployment-intake.js';

test('deployment intake requires and trims Idempotency-Key before multipart parsing', async () => {
  const missing = readDeploymentIntakeHeaders(
    new Request('https://api.pages.xd.team/.xd-pages/api/deployments', {
      method: 'POST',
      headers: { 'Content-Type': 'multipart/form-data' },
    })
  );
  assert.equal(missing.ok, false);
  assert.equal(missing.response.status, 400);
  assert.deepEqual(await missing.response.json(), {
    error: {
      code: 'IDEMPOTENCY_KEY_REQUIRED',
      message: 'Idempotency-Key is required.',
      action: 'Send an Idempotency-Key header.',
    },
  });
  assert.deepEqual(missing.traceFailure, {
    stage: 'intake',
    operation: 'read_idempotency_key',
    errorCode: 'IDEMPOTENCY_KEY_REQUIRED',
    errorMessage: 'Idempotency-Key is required.',
    diagnostics: { causeClass: 'request_validation_error' },
  });

  const accepted = readDeploymentIntakeHeaders(
    new Request('https://api.pages.xd.team/.xd-pages/api/deployments', {
      method: 'POST',
      headers: {
        'Content-Type': 'multipart/form-data; boundary=test',
        'Idempotency-Key': '  deploy_1  ',
      },
    })
  );
  assert.deepEqual(accepted, { ok: true, idempotencyKey: 'deploy_1' });
});

test('deployment intake rejects non-CLI upload protocols with stable trace metadata', async () => {
  const result = readDeploymentIntakeHeaders(
    new Request('https://api.pages.xd.team/.xd-pages/api/deployments', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'deploy_1' },
    })
  );

  assert.equal(result.ok, false);
  assert.deepEqual(await result.response.json(), {
    error: {
      code: 'CLI_UPLOAD_PROTOCOL_REQUIRED',
      message: 'Deployment uploads must be generated by the XD Cell CLI.',
      action: 'Run `xd-cell deploy` or `xd-cell deploy --dry-run --json` and retry.',
    },
  });
  assert.deepEqual(result.traceFailure, {
    stage: 'intake',
    operation: 'parse_multipart',
    errorCode: 'CLI_UPLOAD_PROTOCOL_REQUIRED',
    errorMessage: 'Deployment uploads must use the CLI protocol.',
    diagnostics: { causeClass: 'payload_validation_error' },
  });
});

test('deployment multipart errors preserve stable response and explicit trace mappings', async () => {
  const cases = [
    ['PAYLOAD_TOO_LARGE', 413, 'PAYLOAD_TOO_LARGE'],
    ['ASSET_MANIFEST_INVALID', 400, 'ASSET_MANIFEST_INVALID'],
    ['ASSET_FILES_REQUIRED', 400, 'ASSET_FILES_REQUIRED'],
    ['FALLBACK_REQUIRES_ASSETS', 400, 'FALLBACK_REQUIRES_ASSETS'],
    ['FALLBACK_INDEX_REQUIRES_INDEX_HTML', 400, 'FALLBACK_INDEX_REQUIRES_INDEX_HTML'],
    ['PUBLISH_PLAN_VERSION_UNSUPPORTED', 400, 'PUBLISH_PLAN_VERSION_UNSUPPORTED'],
    ['PUBLISH_PLAN_INVALID', 400, 'PUBLISH_PLAN_INVALID'],
    ['RUNTIME_VARS_INVALID', 400, 'RUNTIME_VARS_INVALID'],
    ['RUNTIME_VARS_LIMIT_EXCEEDED', 400, 'RUNTIME_BINDINGS_LIMIT_EXCEEDED'],
  ];

  for (const [inputCode, status, responseCode] of cases) {
    const result = deploymentMultipartError({ code: inputCode });
    assert.equal(result.ok, false);
    assert.equal(result.response.status, status);
    assert.equal((await result.response.json()).error.code, responseCode);
    assert.equal(result.traceFailure, undefined);
  }

  const contentHash = deploymentMultipartError({ code: 'CONTENT_HASH_MISMATCH' });
  assert.equal((await contentHash.response.json()).error.code, 'CONTENT_HASH_MISMATCH');
  assert.deepEqual(contentHash.traceFailure, {
    stage: 'payload_validation',
    operation: 'validate_content_hash',
    errorCode: 'CONTENT_HASH_MISMATCH',
    errorMessage: 'Content hash does not match uploaded files.',
    diagnostics: { causeClass: 'payload_validation_error' },
  });

  const malformed = deploymentMultipartError(new TypeError('malformed form data'));
  assert.equal((await malformed.response.json()).error.code, 'INVALID_MULTIPART');
  assert.equal(malformed.traceFailure.operation, 'parse_multipart');
});

test('rollback intake parses an optional bounded JSON object and maps invalid input', async () => {
  const accepted = await readRollbackIntake(
    new Request('https://api.pages.xd.team/.xd-pages/api/versions/ver_1/rollback', {
      method: 'POST',
      headers: { 'Idempotency-Key': '  rollback_1  ' },
      body: JSON.stringify({ siteId: 'site_1' }),
    })
  );
  assert.deepEqual(accepted, { ok: true, idempotencyKey: 'rollback_1', body: { siteId: 'site_1' } });

  const invalid = await readRollbackIntake(
    new Request('https://api.pages.xd.team/.xd-pages/api/versions/ver_1/rollback', {
      method: 'POST',
      headers: { 'Idempotency-Key': 'rollback_2' },
      body: '[]',
    })
  );
  assert.equal(invalid.ok, false);
  assert.equal((await invalid.response.json()).error.code, 'INVALID_JSON');
  assert.deepEqual(invalid.traceFailure, {
    stage: 'intake',
    operation: 'parse_json',
    errorCode: 'INVALID_JSON',
    errorMessage: 'Invalid JSON body.',
    diagnostics: { causeClass: 'payload_validation_error' },
  });
});
